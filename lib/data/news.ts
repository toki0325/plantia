export function getNewsById(id: string): NewsItem | undefined {
  return newsItems.find((n) => n.id === id);
}

export function getLatestNews(limit = 3): NewsItem[] {
  return [...newsItems]
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))
    .slice(0, limit);
}
